class 流程控制器:
    def __init__(self, 插件管理器实例: 插件管理器, 数据管理器: 运行数据管理器) -> None:
        self.插件管理器 = 插件管理器实例
        self.数据管理器 = 数据管理器

    def 执行颅骨透明化用途流程(self, 数据上下文: dict[str, Any]) -> dict[str, Any]:
        return 运行颅骨透明化流程(数据上下文, self.插件管理器.获取插件)

    def 执行补充数据3真实流程(self) -> dict[str, Any]:
        上下文 = {"数据管理器": self.数据管理器}
        导入 = self.插件管理器.获取插件("论文表格导入").执行(上下文)
        结构 = self.插件管理器.获取插件("RDKit结构处理").执行(上下文)
        描述符 = self.插件管理器.获取插件("RDKit普通描述符").执行(上下文)
        距离 = self.插件管理器.获取插件("汉森距离计算").执行(上下文)
        合并 = self.插件管理器.获取插件("化学属性合并").执行(上下文)
        return {
            "导入候选数量": len(导入),
            "结构成功数量": int(结构["结构状态"].eq("已获得").sum()),
            "描述符成功数量": int(描述符.loc[描述符["是否计算成功"], "候选编号"].nunique()),
            "汉森距离记录数量": len(距离),
            "统一记录数量": len(合并),
        }

    def 执行用户候选导入(
        self,
        文件名: str,
        文件内容: bytes,
        字段映射: dict[str, str | None],
        用户筛选设置: dict[str, Any] | None = None,
        候选类型: str = "通用候选",
        应用配置: str | None = None,
    ) -> dict[str, Any]:
        设置 = dict(用户筛选设置 or {})
        配置编号 = str(应用配置 or 设置.get("应用配置") or "user_custom")
        设置["应用配置"] = 配置编号
        run_id = self.数据管理器.创建运行(
            配置编号,
            文件名,
            {"候选类型": 候选类型, "规则启用覆盖": 设置.get("规则启用覆盖", {})},
        )
        上下文 = {
            "数据管理器": self.数据管理器,
            "运行编号": run_id,
            "文件名": 文件名,
            "文件内容": 文件内容,
            "字段映射": 字段映射,
            "候选类型": 候选类型,
            "应用配置": 配置编号,
        }
        导入 = self.插件管理器.获取插件("通用候选表导入").执行(上下文)
        身份 = self.插件管理器.获取插件("化合物身份转换").执行({
            "数据管理器": self.数据管理器,
            "身份输入标识": "用户导入_统一候选记录",
            "身份输出标识": "用户导入_化合物身份映射",
            "允许网络身份查询": bool(设置.get("允许网络身份查询", False)),
        })
        结构 = self.插件管理器.获取插件("RDKit结构处理").执行({"数据管理器": self.数据管理器, "用户结构处理": True})
        描述符 = self.插件管理器.获取插件("RDKit普通描述符").执行({"数据管理器": self.数据管理器, "用户描述符处理": True})
        HSP初筛 = self.插件管理器.获取插件("用户候选HSP初筛").执行({"数据管理器": self.数据管理器})
        筛选 = self.插件管理器.获取插件("用户候选规则筛选").执行({
            "数据管理器": self.数据管理器,
            "用户筛选设置": 设置,
            "候选输入标识": "用户导入_HSP初筛记录",
        })
        报告 = self.插件管理器.获取插件("通用运行报告导出").执行({
            "数据管理器": self.数据管理器,
            "运行编号": run_id,
            "应用配置": 配置编号,
        })
        return {
            "run_id": run_id,
            "应用配置": 配置编号,
            "导入记录数": len(导入),
            "身份已匹配数": int(身份["匹配状态"].astype(str).str.startswith("已匹配").sum()),
            "待人工确认数": int(身份["匹配状态"].eq("待人工确认").sum()),
            "结构成功数": int(结构["结构状态"].eq("已获得").sum()),
            "HSP已计算数": int(HSP初筛.get("与BA的HSP状态", pd.Series(dtype=str)).eq("已计算").sum()),
            "规则通过数": int(筛选["规则总状态"].eq("通过").sum()),
            "无法评估数": int(筛选["规则总状态"].eq("无法评估").sum()),
            "跳过规则数": int(筛选["规则总状态"].eq("跳过").sum()),
            "报告路径": str(报告),
        }

    def 执行补充数据2规则筛选流程(self, 启用网络查询: bool = False) -> dict[str, Any]:
        """保留论文复现入口；最终10标签仅在合并后可选对照，不参与筛选。"""
        上下文 = {"数据管理器": self.数据管理器}
        导入 = self.插件管理器.获取插件("补充数据2表格导入").执行(上下文)
        规则 = self.插件管理器.获取插件("规则筛选")
        初筛 = 规则.执行数值初筛(上下文)
        身份 = self.插件管理器.获取插件("化合物身份转换").执行({
            **上下文,
            "身份输入标识": "补充数据2_数值初筛记录",
            "身份输出标识": "补充数据2_41候选身份映射",
            "允许网络身份查询": 启用网络查询,
        })
        结构 = self.插件管理器.获取插件("RDKit结构处理").执行({**上下文, "补充数据2结构处理": True})
        描述符 = self.插件管理器.获取插件("RDKit普通描述符").执行({**上下文, "补充数据2描述符处理": True})
        距离 = self.插件管理器.获取插件("补充数据2汉森距离计算").执行(上下文)
        自动 = 规则.执行最终自动规则筛选(上下文)
        合并 = self.插件管理器.获取插件("补充数据2属性合并").执行(上下文)
        冲突 = self.插件管理器.获取插件("官方数据冲突检测").执行(上下文)
        PubChem证据 = self.插件管理器.获取插件("PubChem查询").执行({**上下文, "启用网络毒性查询": 启用网络查询})
        CompTox状态 = self.插件管理器.获取插件("CompTox接口状态").执行(上下文)
        毒性视图 = self.插件管理器.获取插件("毒性证据视图").执行(上下文)
        动物模型 = 毒性视图.get("动物模型", 毒性视图.get("动物模型结果", []))
        报告 = self.插件管理器.获取插件("筛选报告导出").执行(上下文)
        图表 = (
            self.插件管理器.获取插件("筛选结果图表").执行(上下文)
            if 启用结果可视化()
            else {}
        )
        自动通过 = 自动["自动规则通过"].astype(str).str.lower().eq("true")
        最终标签 = 合并.get("论文最终10候选标签", pd_series(合并.index, "")).eq("是")
        return {
            "清理后真实候选数": len(导入),
            "数值初筛通过数": int(初筛["数值初筛通过"].astype(str).str.lower().eq("true").sum()),
            "身份处理数": len(身份),
            "结构成功数": int(结构["结构状态"].eq("已获得").sum()),
            "描述符成功数": int(描述符.loc[描述符["是否计算成功"], "候选编号"].nunique()),
            "汉森距离记录数量": len(距离),
            "自动规则最终剩余数": int(自动通过.sum()),
            "论文最终10恢复数": int((自动通过 & 最终标签).sum()),
            "官方数据冲突数": len(冲突),
            "PubChem毒性证据数": len(PubChem证据),
            "CompTox状态数": len(CompTox状态),
            "动物模型记录数": len(动物模型),
            "报告路径": str(报告),
            "数量图PNG": str(图表["数量图PNG"]) if 图表 else "",
            "分布图PNG": str(图表["分布图PNG"]) if 图表 else "",
            "结果可视化已启用": 启用结果可视化(),
        }

    def 执行毒理证据匹配(self, 毒理会话: dict[str, Any], 毒理证据: pd.DataFrame) -> dict[str, pd.DataFrame]:
        """执行本地/人工/已启用公开来源的毒理证据匹配。"""
        return self.插件管理器.获取插件("毒理证据匹配").执行({
            "数据管理器": self.数据管理器,
            "毒理会话": 毒理会话,
            "毒理证据": 毒理证据,
        })

    def 执行公开证据查询(self, 数据上下文: dict[str, Any]) -> dict[str, Any]:
        """显式查询公开来源并按条件生成采用结果，证据不进入 descriptor 宽表。"""
        return self.插件管理器.获取插件("公开证据聚合").执行({"数据管理器": self.数据管理器, **数据上下文})

    def 执行毒理公开数据查询(self, 毒理会话: dict[str, Any]) -> pd.DataFrame:
        """按会话中勾选的来源查询公开数据；当前仅实现 PubChem GHS。"""
        来源策略 = dict(毒理会话.get("来源策略") or {})
        已启用 = set(来源策略.get("启用公开数据源") or [])
        if "PubChem GHS" not in 已启用:
            return pd.DataFrame()
        批次 = dict(毒理会话.get("化合物批次") or {})
        候选 = pd.DataFrame(毒理会话.get("化合物清单") or [])
        if 候选.empty:
            raise ValueError("公开毒理查询需要一份已确认化合物清单")
        for 字段 in ("批次编号", "来源运行编号", "确认清单标识"):
            候选[字段] = str(批次.get(字段, ""))
        return self.插件管理器.获取插件("公开证据聚合").执行({
            "数据管理器": self.数据管理器,
            "公开毒理候选": 候选,
            "允许使用缓存": bool(来源策略.get("是否允许缓存结果", True)),
        })


def pd_series(index: Any, 值: Any):
    import pandas as pd
    return pd.Series(值, index=index)


